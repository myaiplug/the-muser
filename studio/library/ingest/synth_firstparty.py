def main():
    import argparse, sys
    ap = argparse.ArgumentParser()
    ap.add_argument("--audio-dir", default=str(LIB / "audio"))
    a = ap.parse_args()
    from pathlib import Path
    recs = []
    for cat, title, extra, fn in jobs():
        sid = "nodaw-" + slug(title)
        rng = seeded(sid)
        x = finish(fn(rng))
        rel = f"audio/nodaw-synth/{sid}.flac"
        info = write_flac(x, Path(a.audio_dir).parent / rel if a.audio_dir != str(LIB / "audio") else LIB / rel)
        recs.append(make_record(
            sid=sid, title=title, category=cat, source="nodaw-synth", license="CC0-1.0", license_url=CC0,
            author=AUTHOR, source_url=SRC_URL, provenance="first-party", file=rel, audio_info=info,
            extra_tags=["synthetic", *extra],
            processing="synthesised in numpy, trimmed, faded, peak-normalised to -1 dBFS, FLAC 16-bit 44.1 kHz",
            notes="Rendered from code; deterministic seed. Genre assignment follows the category.",
        ))
    save_records("nodaw-synth", recs)


if __name__ == "__main__":
    main()
