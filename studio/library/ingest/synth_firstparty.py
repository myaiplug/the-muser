def t_axis(n):
    return np.arange(int(SR * n)) / SR


def hp(x, f, o=2):
    return signal.sosfilt(signal.butter(o, f, "hp", fs=SR, output="sos"), x)


def lp(x, f, o=2):
    return signal.sosfilt(signal.butter(o, min(f, SR / 2 - 100), "lp", fs=SR, output="sos"), x)


def bp(x, lo, hi, o=2):
    return signal.sosfilt(signal.butter(o, [lo, min(hi, SR / 2 - 100)], "bp", fs=SR, output="sos"), x)


def noise(rng, n):
    return rng.standard_normal(int(SR * n))


def kick(rng, f0, f1, sweep, decay, drive, click, ln, **_):
    t = t_axis(ln)
    f = f1 + (f0 - f1) * np.exp(-sweep * t)
    ph = 2 * np.pi * np.cumsum(f) / SR
    y = np.tanh(drive * np.sin(ph)) * np.exp(-decay * t)
    c = hp(noise(rng, ln), 2500) * np.exp(-400 * t) * click
    return y + c


def snare(rng, tone, toneDecay, toneLevel, noiseDecay, noiseLevel, hpf, ln, lpf=None, **_):
    t = t_axis(ln)
    f = tone * (1 + 0.5 * np.exp(-60 * t))
    body = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-toneDecay * t) * toneLevel
    n = hp(noise(rng, ln), hpf) * np.exp(-noiseDecay * t) * noiseLevel
    if lpf:
        n = lp(n, lpf)
    return body + n


def clap(rng, bursts=4, gap=0.011, f_lo=900, f_hi=3200, tail=22, ln=0.35, width=0.9, **_):
    t = t_axis(ln)
    y = np.zeros_like(t)
    nz = bp(noise(rng, ln), f_lo, f_hi)
    for i in range(bursts):
        s = int(i * gap * SR)
        env = np.zeros_like(t)
        m = len(t) - s
        env[s:] = np.exp(-np.arange(m) / SR * (700 if i < bursts - 1 else tail))
        y += nz * env * (0.8 if i < bursts - 1 else 1.0)
    return y * width + bp(noise(rng, ln), f_lo * 1.3, f_hi * 1.2) * np.exp(-tail * t) * 0.3


RATIOS808 = np.array([2.0, 3.0, 4.16, 5.43, 6.79, 8.21])


def hat808(rng, decay, hpf=7000, base=205.3, ln=0.5, tone=1.0, **_):
    t = t_axis(ln)
    y = sum(np.sign(np.sin(2 * np.pi * base * r * t)) for r in RATIOS808) * tone
    y = hp(y, hpf, 4) + 0.35 * hp(noise(rng, ln), hpf)
    return y * np.exp(-decay * t)


def hat_noise(rng, decay, hpf=6500, lpf=None, ln=0.4, **_):
    t = t_axis(ln)
    y = hp(noise(rng, ln), hpf, 3)
    if lpf:
        y = lp(y, lpf)
    return y * np.exp(-decay * t)


def sine_hit(f0, f1, sweep, decay, ln, drive=1.0, **_):
    t = t_axis(ln)
    f = f1 + (f0 - f1) * np.exp(-sweep * t)
    return np.tanh(drive * np.sin(2 * np.pi * np.cumsum(f) / SR)) * np.exp(-decay * t)


def tom(rng, f, decay=9, ln=0.6, sweep=18, **_):
    return sine_hit(f * 1.6, f, sweep, decay, ln, 1.2) + 0.15 * bp(noise(rng, ln), 800, 4000) * np.exp(-60 * t_axis(ln))


def rim(rng, f1=1700, f2=480, ln=0.12, **_):
    t = t_axis(ln)
    return (np.sin(2 * np.pi * f1 * t) * 0.6 + np.sin(2 * np.pi * f2 * t) * 0.8) * np.exp(-90 * t) + hp(noise(rng, ln), 3000) * np.exp(-250 * t) * 0.4


def cowbell(rng, f1=587, f2=845, decay=14, ln=0.5, **_):
    t = t_axis(ln)
    y = np.sign(np.sin(2 * np.pi * f1 * t)) + np.sign(np.sin(2 * np.pi * f2 * t))
    return bp(y, 500, 3500) * (0.7 * np.exp(-decay * t) + 0.3 * np.exp(-3 * t))


def shaker(rng, lo=4500, hi=11000, attack=0.025, decay=18, ln=0.3, **_):
    t = t_axis(ln)
    env = np.minimum(t / attack, 1.0) * np.exp(-decay * np.maximum(t - attack, 0))
    return bp(noise(rng, ln), lo, hi) * env


def tambourine(rng, ln=0.6, **_):
    t = t_axis(ln)
    jingle = sum(np.sin(2 * np.pi * f * t + rng.uniform(0, 6)) for f in (5600, 6800, 8100, 9400, 10700))
    y = hp(noise(rng, ln), 5000) * np.exp(-18 * t) + 0.25 * jingle * np.exp(-14 * t)
    return y * np.minimum(t / 0.004, 1.0)


def conga(rng, f=210, ln=0.5, slap=False, **_):
    t = t_axis(ln)
    y = sine_hit(f * 1.25, f, 40, 11 if not slap else 16, ln) + 0.4 * sine_hit(f * 2.1, f * 2.0, 40, 22, ln)
    return y + (bp(noise(rng, ln), 1200, 5000) * np.exp(-120 * t) * (0.7 if slap else 0.25))


def clave(rng, f=2500, ln=0.25, **_):
    t = t_axis(ln)
    return np.sin(2 * np.pi * f * t) * np.exp(-60 * t) + 0.3 * np.sin(2 * np.pi * f * 1.5 * t) * np.exp(-80 * t)


def snap(rng, ln=0.25, **_):
    t = t_axis(ln)
    y = bp(noise(rng, ln), 1400, 4200, 3) * np.exp(-85 * t)
    return y + 0.3 * sine_hit(900, 600, 80, 60, ln)


def woodblock(rng, f=1100, ln=0.3, **_):
    t = t_axis(ln)
    return (np.sin(2 * np.pi * f * t) + 0.5 * np.sin(2 * np.pi * f * 2.76 * t)) * np.exp(-45 * t)


def bass808(rng, note_hz, decay=2.2, drive=1.8, glide=0.03, ln=1.6, start=2.4, click=0.2, dist=None, **_):
    t = t_axis(ln)
    f = note_hz * (1 + (start - 1) * np.exp(-t / glide * 3))
    y = np.sin(2 * np.pi * np.cumsum(f) / SR)
    y = np.tanh(drive * y)
    if dist:
        y = np.tanh(dist * y) + 0.15 * np.tanh(dist * 3 * np.sin(2 * np.pi * np.cumsum(f * 2) / SR))
    env = np.exp(-decay * t) * np.minimum(t / 0.002, 1.0)
    return y * env + hp(noise(rng, ln), 3000) * np.exp(-700 * t) * click * 0.5


def cymbal(rng, decay, base=300, hpf=3500, ln=3.0, bell=0.0, **_):
    t = t_axis(ln)
    parts = sum(np.sign(np.sin(2 * np.pi * base * r * t + rng.uniform(0, 6)))
                for r in (1.0, 1.34, 1.78, 2.31, 2.89, 3.51, 4.37, 5.29, 6.43, 7.7))
    y = hp(parts, hpf, 3) * 0.6 + hp(noise(rng, ln), hpf, 2)
    env = np.exp(-decay * t) * np.minimum(t / 0.002, 1.0)
    y = y * env
    if bell:
        y += bell * np.sin(2 * np.pi * 3100 * t) * np.exp(-6 * t)
    return y


