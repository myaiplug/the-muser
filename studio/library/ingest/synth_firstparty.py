def seeded(sid):
    import hashlib
    return np.random.default_rng(int(hashlib.sha256(sid.encode()).hexdigest()[:8], 16))


def variant(p, v, keys_up=(), keys_down=()):
    """v=0 preset, v=1 detuned/shortened, v=2 longer/brighter."""
    q = dict(p)
    k = [1.0, 0.9, 1.12][v]
    for key in keys_up:
        if key in q:
            q[key] = q[key] * k
    for key in keys_down:
        if key in q:
            q[key] = q[key] / k
    return q


