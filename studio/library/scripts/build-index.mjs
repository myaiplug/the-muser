// Merge data/records/*.json, validate everything (including files on disk), then write
// sounds.json (static export for the serverless demo) and ATTRIBUTIONS.md.
// Exits non-zero if any record is invalid.
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { LIB_DIR } from '../src/db.mjs'
import { validateAll } from '../src/validate.mjs'
import { ALLOWED } from '../src/licenses.mjs'
import { CATEGORY_BY_ID } from '../taxonomy/taxonomy.mjs'

const recDir = path.join(LIB_DIR, 'data/records')
const records = fs.readdirSync(recDir).filter((f) => f.endsWith('.json')).sort()
  .flatMap((f) => JSON.parse(fs.readFileSync(path.join(recDir, f), 'utf8')))

// type is derived from category so records cannot disagree with the taxonomy
for (const r of records) if (!r.type && CATEGORY_BY_ID[r.category]) r.type = CATEGORY_BY_ID[r.category].type

const v = validateAll(records)
const problems = v.bad.map((b) => `${b.id}: ${b.errors.join('; ')}`)
for (const r of records) {
  const p = path.join(LIB_DIR, r.file)
  if (!fs.existsSync(p)) { problems.push(`${r.id}: file missing ${r.file}`); continue }
  const buf = fs.readFileSync(p)
  if (crypto.createHash('sha256').update(buf).digest('hex') !== r.sha256) problems.push(`${r.id}: sha256 does not match file`)
  if (buf.length !== r.bytes) problems.push(`${r.id}: byte size does not match file`)
}
if (problems.length) {
  console.error(`INVALID (${problems.length}):\n` + problems.slice(0, 50).join('\n'))
  process.exit(1)
}

records.sort((a, b) => a.id.localeCompare(b.id))
const count = (f) => records.reduce((m, r) => ((m[f(r)] = (m[f(r)] ?? 0) + 1), m), {})
const stats = {
  total: records.length,
  by_type: count((r) => r.type),
  by_category: count((r) => r.category),
  by_license: count((r) => r.license),
  by_source: count((r) => r.source),
  by_provenance: count((r) => r.provenance),
  by_genre: records.flatMap((r) => r.genres).reduce((m, g) => ((m[g] = (m[g] ?? 0) + 1), m), {}),
}
// Deterministic output (no timestamp) so CI diffs stay quiet when nothing changed.
fs.writeFileSync(path.join(LIB_DIR, 'sounds.json'), JSON.stringify({ version: 1, audio_base: 'audio/', stats, sounds: records }, null, 1) + '\n')

const lines = [
  '# Attributions',
  '',
  'Generated by `npm run build` in `studio/library`. Do not edit by hand.',
  '',
  `${records.length} sounds. Every sound below is CC0 or CC BY. CC BY sounds must keep the attribution line shown when redistributed or shipped.`,
  '',
]
const bySource = {}
for (const r of records) (bySource[r.source] ??= []).push(r)
for (const [src, rs] of Object.entries(bySource)) {
  const lic = [...new Set(rs.map((r) => r.license))]
  lines.push(`## ${src}`, '', `${rs.length} sounds. Licence: ${lic.map((l) => `${ALLOWED[l].name} (${ALLOWED[l].canonicalUrl})`).join(', ')}.`, `Author(s): ${[...new Set(rs.map((r) => r.author))].join('; ')}. Source: ${rs[0].source_url}`, '')
  if (lic.some((l) => ALLOWED[l].requiresAttribution) || rs.length <= 60) for (const r of rs) lines.push(`- \`${r.id}\`: ${r.attribution_text}`)
  else lines.push(`CC0 dedication: no attribution required. Per-sound credit lines are in \`sounds.json\` (\`attribution_text\`).`)
  lines.push('')
}
fs.writeFileSync(path.join(LIB_DIR, 'ATTRIBUTIONS.md'), lines.join('\n'))
console.log(`OK ${records.length} sounds -> sounds.json, ATTRIBUTIONS.md`)
console.log(JSON.stringify(stats.by_type), JSON.stringify(stats.by_source))
